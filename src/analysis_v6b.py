#!/usr/bin/env python3
"""Session 6b: batch-size dose-response (pre-registered: audits/P3_preregistration_session6.md).

One sitting (2026-10-25), identical 50-headline seeded sample (seed 20261025),
named protocol, one pass per batch size: B1 (50 singletons, split 25+25 around
the other passes), B5 (10 batches of 5), B25 (2 batches of 25).

Pre-registered predictions:
  P6d  batch-mean variance follows Var(batch mean at size k) = mood^2 + T/k,
       where T = true-score + idiosyncratic variance; intercept (mood^2) > 0
       iff a response-level component exists and is generated by cross-headline
       context (vs. pure per-call serving jitter, which would also appear in
       singletons and is indistinguishable at size 1 -- the dose-response
       separates the two only through the 1/k scaling of the NON-mood part).
  P6e  level by size, two-sided: mean(B1) vs mean(B5) vs mean(B25).

Estimators: mood^2 = (5*v5 - v1)/4 (exact from sizes 1 and 5); 3-point OLS of
v_k on 1/k as a sensitivity check (v25 rests on only 2 batches, low df).
Headline bootstrap B=9999 for the (5v5-v1)/4 estimator. Seed 20261025.
Cross-session comparisons (sessions 1-5 mood estimates) are descriptive only.

Writes: data/results_s6b.json
"""
import json

import numpy as np

DATA = "/home/z/my-project/data"
rng = np.random.default_rng(20261025)
B = 9999

sample = json.load(open(f"{DATA}/s6b_sample.json"))          # 50 urls, corpus order
b1a = json.load(open(f"{DATA}/llm_scores_s6b_b1a.json"))      # first 25, size 1
b1b = json.load(open(f"{DATA}/llm_scores_s6b_b1b.json"))      # last 25, size 1
b5 = json.load(open(f"{DATA}/llm_scores_s6b_b5.json"))         # 50, batches of 5
b25 = json.load(open(f"{DATA}/llm_scores_s6b_b25.json"))       # 50, batches of 25

assert len(sample) == 50
first, second = sample[:25], sample[25:]

B1 = {u: b1a[u] for u in first}
B1.update({u: b1b[u] for u in second})
assert len(B1) == 50 and all(u in b5 and u in b25 for u in sample)

order = sample  # corpus order; batches are consecutive slices

def scores(src):
    return np.array([src[u]["sentiment"] for u in order], dtype=float)

s1, s5, s25 = scores(B1), scores(b5), scores(b25)

means = {"B1": s1.mean(), "B5": s5.mean(), "B25": s25.mean()}
print("levels:", {k: round(v, 3) for k, v in means.items()})

# batch means per size
bm1 = s1                                        # 50 batches of 1
bm5 = s5.reshape(10, 5).mean(axis=1)            # 10 batches of 5
bm25 = s25.reshape(2, 25).mean(axis=1)          # 2 batches of 25

v1 = float(bm1.var(ddof=1))
v5 = float(bm5.var(ddof=1))
v25 = float(bm25.var(ddof=1))
print(f"batch-mean variance: v1={v1:.2f} v5={v5:.2f} v25={v25:.2f}")

# primary estimator: mood^2 = (5*v5 - v1) / 4
mood2 = (5 * v5 - v1) / 4.0
print(f"mood^2 (primary, from sizes 1 and 5): {mood2:.2f}  (mood SD {np.sqrt(max(mood2,0)):.2f} points)")

# bootstrap CI over headlines for the estimator
def mood2_stat(idx):
    x1, x5 = s1[idx], s5[idx]
    m1 = x1.var(ddof=1)
    m5 = np.array([x5[i * 5:(i + 1) * 5].mean() for i in range(10)]).var(ddof=1)
    return (5 * m5 - m1) / 4.0

boot = []
for _ in range(B):
    idx = rng.integers(0, 50, size=50)
    boot.append(mood2_stat(idx))
boot = np.sort(np.array(boot))
ci = [float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5))]
print(f"mood^2 bootstrap 95% CI: [{ci[0]:.2f}, {ci[1]:.2f}]")

# 3-point OLS of v_k on 1/k (sensitivity; v25 has 1 df)
x = np.array([1.0, 0.2, 0.04])
y = np.array([v1, v5, v25])
A = np.column_stack([np.ones(3), x])
coef, *_ = np.linalg.lstsq(A, y, rcond=None)
intercept, slope = float(coef[0]), float(coef[1])
print(f"OLS on 1/k: mood^2 intercept={intercept:.2f}, T (true+idio)={slope:.1f}")

# triangle decomposition: V(a,b) = Var(per-title a-b) = n_a^2 + n_b^2
# (same-title true score cancels; three pairwise variances identify the three
#  per-call noise variances at sizes 1, 5, 25)
V_15 = float((s1 - s5).var(ddof=1))
V_125 = float((s1 - s25).var(ddof=1))
V_525 = float((s5 - s25).var(ddof=1))
n1sq = (V_125 + V_15 - V_525) / 2.0
n5sq = (V_15 + V_525 - V_125) / 2.0
n25sq = (V_125 + V_525 - V_15) / 2.0
print(f"\nper-call noise (triangle): n1={np.sqrt(max(n1sq,0)):.2f} n5={np.sqrt(max(n5sq,0)):.2f} "
      f"n25={np.sqrt(max(n25sq,0)):.2f} (s3 benchmark at size 25: 7.2)")
print(f"n25^2 - n1^2 = {n25sq - n1sq:.1f} (mood^2+position benchmark: ~6.8); "
      f"SE of each V ~ {V_125*np.sqrt(2/49):.0f} -> underpowered for the 6.8 benchmark")

# level contrasts (P6e): paired across sizes on the same 50 titles
def paired_desc(a, b, tag):
    d = a - b
    se = d.std(ddof=1) / np.sqrt(len(d))
    return {"contrast": tag, "mean": float(d.mean()), "se": float(se),
            "t": float(d.mean() / se), "n": 50}

R = {
  "design": {"session": "2026-10-25, single sitting, named protocol",
             "preregistration": "audits/P3_preregistration_session6.md",
             "seed": 20261025, "n_titles": 50, "sizes": [1, 5, 25],
             "pass_order": "B1a(25) -> B25(2) -> B5(10) -> B1b(25)",
             "note": "one pass per size; singleton level centered in session time; "
                     "single-pass-per-size noise bounds level contrasts; "
                     "cross-session comparisons descriptive only"},
  "levels": {k: round(v, 4) for k, v in means.items()},
  "level_contrasts": [paired_desc(s1, s5, "B1_minus_B5"), paired_desc(s1, s25, "B1_minus_B25"),
                      paired_desc(s5, s25, "B5_minus_B25")],
  "batch_mean_variance": {"v_size1": v1, "v_size5": v5, "v_size25": v25},
  "triangle_per_call_noise": {
      "V_1_5": V_15, "V_1_25": V_125, "V_5_25": V_525,
      "n1_sq": n1sq, "n5_sq": n5sq, "n25_sq": n25sq,
      "n1_sd_points": float(np.sqrt(max(n1sq, 0))),
      "n5_sd_points": float(np.sqrt(max(n5sq, 0))),
      "n25_sd_points": float(np.sqrt(max(n25sq, 0))),
      "n25sq_minus_n1sq": n25sq - n1sq,
      "benchmark_s3_mood_sq": 6.76,
      "note": "V(a,b) = n_a^2 + n_b^2 per title; three pairwise variances solve the "
              "three per-call noise variances; SE(V) ~ V*sqrt(2/49), so the ~6.8 "
              "mood^2 benchmark is inside the noise of this single-pass design"},
  "mood2_primary": {"estimate": mood2, "mood_sd_points": float(np.sqrt(max(mood2, 0.0))),
                    "ci95_boot": ci,
                    "share_of_singleton_variance": mood2 / v1 if v1 else None,
                    "formula": "mood^2 = (5*v5 - v1)/4"},
  "ols_1_over_k": {"intercept_mood2": intercept, "slope_true_plus_idio": slope},
  "benchmarks_descriptive": {
      "s3_mood_sd_points": 2.6, "s3_within_sd_points": 7.2,
      "note": "session-3 decomposition from the paper; cross-session, descriptive only"},
}

with open(f"{DATA}/results_s6b.json", "w") as f:
    json.dump(R, f, indent=1)

# sanity: singleton scores vs B25 scores dispersion of means
print("\n=== P6d verdict material ===")
print(f"v1={v1:.2f} vs 5*v5={5*v5:.2f}: {'mood-positive' if 5*v5 > v1 else 'no mood'}")
print(f"mood^2 = {mood2:.2f} -> mood SD = {np.sqrt(max(mood2,0)):.2f} pts "
      f"(benchmark s3: 2.6 pts); share of singleton variance = {mood2/v1:.1%}")
print(f"headline-bootstrap CI on mood^2 is wide and headline resampling cannot "
      f"represent call-level mood variation -> decomposition underpowered")
print(f"levels B1={means['B1']:.2f} B5={means['B5']:.2f} B25={means['B25']:.2f}")
for c in R["level_contrasts"]:
    print(f"  {c['contrast']}: {c['mean']:+.3f} (se {c['se']:.3f}, t {c['t']:+.2f})")
print("saved -> data/results_s6b.json")
