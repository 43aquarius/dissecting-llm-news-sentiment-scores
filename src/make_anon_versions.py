#!/usr/bin/env python3
"""Generate the double-anonymized FRL review versions from the author-full versions.

Elsevier double-anonymized submission requires:
  * a separate Title Page (with author details)          -> frl_titlepage.tex (hand-written)
  * a Manuscript without author details                  -> frl_letter_anon.tex   (generated here)
  * supplementary material must also be identification-free -> online_appendix_anon.tex (generated here)

This script performs surgical, exact-string replacements on the two author-full
sources, fails loudly if a source pattern drifted, and self-checks that the
generated files contain zero identifying strings. It also asserts that the
anonymous letter is line-identical to the full letter outside the title block.

Run:  python3 scripts/make_anon_versions.py
"""
import re
import sys
from pathlib import Path

# Two supported layouts:
#   working copy:  /home/z/my-project  (submission_frl/, paper/, scripts/)
#   repository:    github_repo / replication_package_v2  (submission/, paper/, src/)
CAND = [Path("/home/z/my-project"),
        Path(__file__).resolve().parent.parent]
ROOT = next((p for p in CAND
             if (p / "submission_frl/frl_letter.tex").exists()
             or (p / "submission/frl_letter.tex").exists()), CAND[0])
SUB = "submission_frl" if (ROOT / "submission_frl").is_dir() else "submission"
LETTER = ROOT / SUB / "frl_letter.tex"
LETTER_ANON = ROOT / SUB / "frl_letter_anon.tex"
OA = ROOT / "paper/online_appendix.tex"
OA_ANON = ROOT / "paper/online_appendix_anon.tex"

IDENTIFIERS = ["Chang Tan", "Dalian University", "aquars43", "foxmail",
               "43aquarius", "github.com"]

HEADER_NOTE = ("% -------------------------------------------------------------\n"
              "% ANONYMIZED REVIEW VERSION - generated by scripts/make_anon_versions.py\n"
              "% from the author-full version; do not edit by hand. Regenerate with:\n"
              "%   python3 scripts/make_anon_versions.py\n"
              "% -------------------------------------------------------------\n")


def must_replace(text, old, new, label):
    if old not in text:
        sys.exit(f"ABORT: source pattern for [{label}] not found — source drifted:\n  {old[:90]}...")
    return text.replace(old, new, 1)


def check_clean(path, what):
    text = path.read_text()
    hits = [s for s in IDENTIFIERS if s in text]
    if hits:
        sys.exit(f"ABORT: {what} still contains identifying strings: {hits}")
    print(f"  {what}: zero identifying strings  ✓")


# ---------------------------------------------------------------- letter ----
src = LETTER.read_text()

# 1. footnote: replace the repository URL with a neutral pointer
src = must_replace(
    src,
    ("is available at \\url{https://github.com/43aquarius/"
     "dissecting-llm-news-sentiment-scores}. This letter is a compressed version"),
    ("is available from the corresponding author and from the public "
     "repository listed on the title page. This letter is a compressed version"),
    "letter URL footnote")

# 2. author block -> empty (double-anonymized)
src = must_replace(
    src,
    "\\author{Chang Tan\\thanks{Dalian University of Technology. "
    "Email: aquars43@foxmail.com.}}",
    "\\author{}",
    "letter author block")

# 3. add the generation note under the existing header comments
src = src.replace("\\documentclass[11pt]{article}",
                  HEADER_NOTE + "\\documentclass[11pt]{article}", 1)
LETTER_ANON.write_text(src)

# ------------------------------------------------------- online appendix ----
src = OA.read_text()

# 1. PDF metadata author
src = must_replace(src, "    pdfauthor={Chang Tan},", "    pdfauthor={},",
                   "OA pdfauthor metadata")

# 2. title-block author line
src = must_replace(src, "{\\normalsize Chang Tan}\\par\n",
                   "{\\normalsize\\color{darkgray} Prepared for double-anonymized review}\\par\n",
                   "OA author line")

# 3. affiliation/email line (keep the date)
src = must_replace(
    src,
    "{\\small\\color{darkgray} Dalian University of Technology \\quad$\\cdot$\\quad "
    "aquars43@foxmail.com \\quad$\\cdot$\\quad October 2026}\\par",
    "{\\small\\color{darkgray} October 2026}\\par",
    "OA affiliation line")

src = src.replace("\\documentclass[11pt,a4paper]{article}",
                  HEADER_NOTE + "\\documentclass[11pt,a4paper]{article}", 1)
OA_ANON.write_text(src)

# ---------------------------------------------------------------- checks ----
check_clean(LETTER_ANON, "frl_letter_anon.tex")
check_clean(OA_ANON, "online_appendix_anon.tex")

# anonymous letter must be line-identical to the full letter outside the
# header block. Align by applying the same header-note insertion to the
# full source in memory, then require diffs only on the title/author lines.
full_aligned = LETTER.read_text().replace(
    "\\documentclass[11pt]{article}",
    HEADER_NOTE + "\\documentclass[11pt]{article}", 1)
full_lines = full_aligned.splitlines()
anon_lines = LETTER_ANON.read_text().splitlines()
if len(full_lines) != len(anon_lines):
    sys.exit(f"ABORT: line count changed ({len(full_lines)} -> {len(anon_lines)})")
diff_rows = [i + 1 for i, (a, b) in enumerate(zip(full_lines, anon_lines)) if a != b]
expected_rows = {25, 26}   # title footnote line + author line (shifted by the header note)
unexpected = [r for r in diff_rows if r not in expected_rows]
if unexpected:
    sys.exit(f"ABORT: unexpected diffs outside the title block at lines {unexpected}")
print(f"  frl_letter_anon.tex: only title-block lines differ ({diff_rows})  ✓")
print("\nmake_anon_versions: OK")
