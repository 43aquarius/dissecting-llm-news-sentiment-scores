#!/usr/bin/env python3
"""P0-1: Rebuild Table 6 (firm-level news coverage) from archived artifacts.

Replaces the unauditable hand-assembled table (37 tickers incl. ghost VZ row,
totals 491/233) with a script-generated one.

Definitions (each cell traceable to raw files):
  articles_in_window  : news_all.json articles with date_iso in [2026-07-01, 2026-10-14]
  firm_days_trading   : unique (ticker, date_iso) with scored relevance >= 30 AND
                        date_iso is a trading date present in panel.csv
Verification targets: 36 tickers, column sums 341 and 240 (= regression sample).

Outputs:
  data/coverage_table.json                (machine-readable, for regression tests)
  paper/sections/gen/table_coverage.tex   (LaTeX table body, \\input-ed by appendix.tex)
"""
import json
import os
import pandas as pd

DATA = "/home/z/my-project/data"
OUT_JSON = f"{DATA}/coverage_table.json"
OUT_TEX = "/home/z/my-project/paper/sections/gen/table_coverage.tex"
WINDOW = ("2026-07-01", "2026-10-14")
REL_MIN = 30

arts = json.load(open(f"{DATA}/news_all.json"))
orig = json.load(open(f"{DATA}/llm_scores.json"))
panel = pd.read_csv(f"{DATA}/panel.csv", parse_dates=["date"])

# ---- in-window articles ----
iw = [a for a in arts if a.get("date_iso") and WINDOW[0] <= a["date_iso"] <= WINDOW[1]]
n_art = pd.Series([a["ticker"] for a in iw]).value_counts()

# ---- relevance-qualified firm-days on trading days ----
trading_dates = set(panel["date"].dt.strftime("%Y-%m-%d").dropna())
hi = [a for a in iw if (orig.get(a["url"], {}).get("relevance") or 0) >= REL_MIN]
fd_keys = set(f"{a['ticker']}|{a['date_iso']}" for a in hi if a["date_iso"] in trading_dates)
n_fd = pd.Series([k.split("|")[0] for k in fd_keys]).value_counts()

tickers = sorted(set(n_art.index) | set(n_fd.index))
rows = [{"ticker": t,
         "articles_in_window": int(n_art.get(t, 0)),
         "firm_days_trading": int(n_fd.get(t, 0))} for t in tickers]

sum_art = sum(r["articles_in_window"] for r in rows)
sum_fd = sum(r["firm_days_trading"] for r in rows)

# ---- cross-checks against the panel regression sample ----
n_panel_reg = int(panel["llm_sent_rel"].notna().sum())
checks = {
    "n_tickers": len(rows),
    "sum_articles_in_window": sum_art,
    "sum_firm_days_trading": sum_fd,
    "panel_regression_sample": n_panel_reg,
    "chain_341_276_240": {
        "in_window_articles": len(iw),
        "rel30_articles": len(hi),
        "firm_days_rel30_all_calendar": len(set(f"{a['ticker']}|{a['date_iso']}" for a in hi)),
        "firm_days_rel30_non_trading_dropped": len(set(f"{a['ticker']}|{a['date_iso']}" for a in hi)) - sum_fd,
    },
    "assertions": {
        "36_tickers": len(rows) == 36,
        "sum_341": sum_art == 341,
        "sum_240_matches_panel": sum_fd == n_panel_reg,
        "no_ghost_rows": "VZ" not in tickers,
    },
}

# ---- LaTeX: 3-column-pair layout identical to previous style ----
def cell(t, a, f):
    return f"{t} & {a} & {f}"

n = len(rows)
third = (n + 2) // 3
cols = [rows[0:third], rows[third:2 * third], rows[2 * third:n]]
lines = []
rendered = []
for i in range(third):
    parts = []
    for c in cols:
        if i < len(c):
            parts.append(f"{c[i]['ticker']} & {c[i]['articles_in_window']} & {c[i]['firm_days_trading']}")
            rendered.append(c[i])
        else:
            parts.append("~--- & ~--- & ~---")
    lines.append(" & ".join(parts) + " \\\\")

# ---- rendered-cell assertions (the data checks above do not see the layout) ----
rendered_tickers = [r["ticker"] for r in rendered]
assert len(rendered_tickers) == len(set(rendered_tickers)) == len(rows), \
    f"rendered table must show each ticker exactly once: {len(set(rendered_tickers))} unique of {len(rows)}"
assert sorted(rendered_tickers) == sorted(r["ticker"] for r in rows), "rendered tickers != data tickers"
assert sum(r["articles_in_window"] for r in rendered) == sum_art, "rendered article sum != data sum"
assert sum(r["firm_days_trading"] for r in rendered) == sum_fd, "rendered firm-day sum != data sum"
checks["assertions"].update({
    "rendered_unique_tickers": len(set(rendered_tickers)) == len(rows),
    "rendered_sums_match": (sum(r["articles_in_window"] for r in rendered) == sum_art
                             and sum(r["firm_days_trading"] for r in rendered) == sum_fd),
})

os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
payload = {"script": "coverage_table.py", "rows": rows, **checks}
json.dump(payload, open(OUT_JSON, "w"), indent=1)

body = "\n".join(lines)
tex = f"""% AUTO-GENERATED by scripts/coverage_table.py -- DO NOT EDIT BY HAND
% Verified: 36 tickers, column sums {sum_art} / {sum_fd}
\\begin{{table}}[tbp]
\\centering
\\small
\\caption{{News coverage by firm (in-window articles and trading-day firm-days)}}
\\label{{tab:coverage}}
\\begin{{adjustbox}}{{max width=\\textwidth}}
\\begin{{tabular}}{{lrr@{{\\hskip 1.6em}}lrr@{{\\hskip 1.6em}}lrr}}
\\toprule
Ticker & Articles & Firm-days & Ticker & Articles & Firm-days & Ticker & Articles & Firm-days \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{adjustbox}}
\\begin{{tablenotes}}[flushleft]\\footnotesize
\\item Articles: headlines dated 2026-07-01 to 2026-10-14 in the archived corpus (column total {sum_art}). Firm-days: unique firm--date cells with scored relevance $\\geq$ 30 falling on a trading date (column total {sum_fd}, equal to the regression sample). {len(set(f"{a['ticker']}|{a['date_iso']}" for a in hi)) - sum_fd} firm--date cells fall on non-trading dates and are dropped without roll-forward (Section~\\ref{{sec:data}}). Computed by \\texttt{{coverage\\_table.py}} from \\texttt{{news\\_all.json}}, \\texttt{{llm\\_scores.json}}, and \\texttt{{panel.csv}}.
\\end{{tablenotes}}
\\end{{table}}
"""
open(OUT_TEX, "w").write(tex)

print(f"tickers: {len(rows)}  articles: {sum_art}  firm-days(trading): {sum_fd}")
print(f"panel regression sample: {n_panel_reg}")
print(f"chain: {len(iw)} articles -> {len(hi)} rel>=30 -> "
      f"{checks['chain_341_276_240']['firm_days_rel30_all_calendar']} firm-days all calendar -> "
      f"{checks['chain_341_276_240']['firm_days_rel30_non_trading_dropped']} non-trading dropped -> {sum_fd}")
print("assertions:", checks["assertions"])
print(f"wrote {OUT_JSON}")
print(f"wrote {OUT_TEX}")
if not all(checks["assertions"].values()):
    raise SystemExit("ASSERTION FAILURE: table does not match verified totals")
